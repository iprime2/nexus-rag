# ------------------------------------------------------------------ migrations


async def test_migrations_match_the_models(engine: AsyncEngine) -> None:
    """Schema drift check: models and migrations must describe the same schema.

    If someone changes a model but forgets the migration (or the reverse),
    autogenerate would find differences, and this test fails.
    """

    def diff(sync_conn: Any) -> list[Any]:
        context = MigrationContext.configure(sync_conn, opts={"compare_type": True})
        differences: list[Any] = compare_metadata(context, Base.metadata)
        return differences

    async with engine.connect() as conn:
        assert await conn.run_sync(diff) == []


async def test_migrations_downgrade_and_upgrade_cleanly(
    db_settings: Settings, engine: AsyncEngine
) -> None:
    async def table_names() -> list[str]:
        async with engine.connect() as conn:
            return await conn.run_sync(lambda c: inspect(c).get_table_names())

    run_alembic(db_settings, "downgrade", "base")
    assert "tenants" not in await table_names()

    run_alembic(db_settings, "upgrade", "head")
    assert "tenants" in await table_names()


# ------------------------------------------------------------------ tenants


async def test_insert_tenant_applies_defaults(
    session_factory: async_sessionmaker[AsyncSession],
) -> None:
    async with session_factory() as session:
        tenant = Tenant(slug="acme", name="Acme Corp")
        session.add(tenant)
        await session.commit()
        await session.refresh(tenant)

    assert tenant.id.version == 7  # generated by the app before INSERT
    assert tenant.status == "active"
    assert tenant.fts_config == "english"
    assert tenant.created_at.tzinfo is not None  # timestamptz, from the database clock


async def test_slug_must_be_unique(session_factory: async_sessionmaker[AsyncSession]) -> None:
    async with session_factory() as session:
        session.add(Tenant(slug="acme", name="First"))
        await session.commit()

    async with session_factory() as session:
        session.add(Tenant(slug="acme", name="Second"))
        with pytest.raises(IntegrityError, match="uq_tenants_slug"):
            await session.commit()


@pytest.mark.parametrize(
    "column,value,constraint",
    [
        ("status", "deleted", "ck_tenants_status"),
        ("slug", "Has Spaces", "ck_tenants_slug_format"),
        ("slug", "trailing-", "ck_tenants_slug_format"),
    ],
)
async def test_check_constraints_reject_invalid_values(
    session_factory: async_sessionmaker[AsyncSession], column: str, value: str, constraint: str
) -> None:
    """The database enforces the rules even if application validation is bypassed."""
    values = {"slug": "valid-slug", "status": "active", column: value}
    async with session_factory() as session:
        with pytest.raises(IntegrityError, match=constraint):
            await session.execute(
                text(
                    "INSERT INTO tenants (id, slug, name, status)"
                    " VALUES (gen_random_uuid(), :slug, 'x', :status)"
                ),
                values,
            )


# ------------------------------------------------------------------ request sessions


async def test_request_session_commits_and_rolls_back(
    db_settings: Settings, session_factory: async_sessionmaker[AsyncSession]
) -> None:
    app = create_app(db_settings)

    @app.post("/tenants/{slug}")
    async def create_tenant(slug: str, session: DbSession, fail: bool = False) -> dict[str, str]:
        session.add(Tenant(slug=slug, name=slug))
        if fail:  # error before commit: the request's session must discard the insert
            raise HTTPException(status_code=500, detail="boom")
        await session.commit()
        return {"slug": slug}

    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://t") as client:
        assert (await client.post("/tenants/kept")).status_code == 200
        assert (await client.post("/tenants/discarded?fail=true")).status_code == 500

    async with session_factory() as session:
        slugs = (await session.scalars(select(Tenant.slug))).all()
    assert slugs == ["kept"]
    await app.state.engine.dispose()
